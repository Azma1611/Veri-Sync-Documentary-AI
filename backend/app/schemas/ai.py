"""
VeriSync AI — AI Assistance Schemas

Pydantic models for structured, validated AI inputs and outputs.
Enforces:
- Strict typing and validation for all LLM responses.
- Clear distinction between deterministic rule findings and AI advisory output.
- Explicit disclaimers preventing misrepresentation as legal proof or fraud detection.
- Zero key leakage in schemas exposed to API consumers.
"""

from __future__ import annotations

from typing import Dict, List, Optional
from pydantic import BaseModel, Field


AI_DISCLAIMER_TEXT = (
    "AI-assisted observation for human reviewer reference only. "
    "Advisory output does not constitute a determination of authenticity, legal validity, or fraud."
)


# ---------------------------------------------------------------------------
# Provider status
# ---------------------------------------------------------------------------

class AIStatusResponse(BaseModel):
    """Status of the backend AI service (no credentials exposed)."""
    enabled: bool = Field(description="Whether AI features are enabled in configuration")
    provider: str = Field(description="Active provider identifier: 'openai', 'mock', 'none'")
    model: str = Field(description="Model identifier configured for analysis")
    configured: bool = Field(description="Whether required credentials or provider clients are ready")
    timeout_seconds: float = Field(description="Configured provider call timeout")
    pii_redaction_enabled: bool = Field(description="Whether PII minimization is active")


# ---------------------------------------------------------------------------
# Finding Explanation
# ---------------------------------------------------------------------------

class AIExplanationRequest(BaseModel):
    """Request to generate an AI explanation for an existing finding."""
    finding_id: str
    rule_id: str
    category: str
    document_a_name: str
    excerpt_a: str
    document_b_name: str
    excerpt_b: str
    current_explanation: Optional[str] = None


class AIExplanationResponse(BaseModel):
    """Validated structured explanation generated by AI."""
    finding_id: str
    summary: str = Field(description="Concise summary of the discrepancy")
    impact_assessment: str = Field(description="Practical contractual or operational risk")
    suggested_action: str = Field(description="Step recommended for the human auditor")
    confidence: float = Field(ge=0.0, le=1.0, description="Model confidence score")
    is_ai_generated: bool = Field(default=True, description="Distinguishes from rule engine")
    disclaimer: str = Field(default=AI_DISCLAIMER_TEXT)


# ---------------------------------------------------------------------------
# Semantic Difference Analysis
# ---------------------------------------------------------------------------

class AISemanticCompareRequest(BaseModel):
    """Request to compare two clause texts for semantic equivalence."""
    clause_type: str = Field(description="e.g. 'ip_assignment', 'notice_period'")
    text_a: str = Field(description="Excerpt from document A")
    doc_name_a: str
    text_b: str = Field(description="Excerpt from document B")
    doc_name_b: str


class AISemanticCompareResponse(BaseModel):
    """Validated semantic comparison output."""
    is_semantic_match: bool = Field(description="Whether the substantive legal intents align")
    similarity_score: float = Field(ge=0.0, le=1.0, description="0.0 to 1.0 semantic similarity")
    substantive_differences: List[str] = Field(default_factory=list, description="Specific terms that differ in meaning")
    key_distinctions: str = Field(description="Human-readable synthesis of differences")
    confidence: float = Field(ge=0.0, le=1.0)
    is_ai_generated: bool = Field(default=True)
    disclaimer: str = Field(default=AI_DISCLAIMER_TEXT)


# ---------------------------------------------------------------------------
# Candidate Field Extraction
# ---------------------------------------------------------------------------

class CandidateFieldItem(BaseModel):
    """A candidate field extracted by AI from untrusted document text."""
    field_name: str
    raw_value: str
    normalized_value: Optional[str] = None
    exact_quote: str = Field(description="Verbatim excerpt from document text")
    confidence: float = Field(ge=0.0, le=1.0)
    is_grounded: bool = Field(
        default=False,
        description="True only if confirmed by GroundingValidator against source blocks",
    )
    grounded_page: Optional[int] = None
    grounded_paragraph: Optional[str] = None


class AICandidateFieldExtractionRequest(BaseModel):
    """Request to extract candidate fields from document text."""
    document_name: str
    document_id: Optional[str] = None
    document_text: str = Field(description="Raw text or excerpt from document")
    target_fields: List[str] = Field(
        default_factory=lambda: ["salary", "probation", "notice", "ip_assignment", "reporting_manager"],
        description="List of fields to detect",
    )


class AICandidateFieldExtractionResponse(BaseModel):
    """Structured extraction response with grounding flags."""
    document_name: str
    document_id: Optional[str] = None
    extracted_fields: List[CandidateFieldItem]
    grounded_count: int = Field(default=0)
    unverified_count: int = Field(default=0)
    is_ai_generated: bool = Field(default=True)
    disclaimer: str = Field(default=AI_DISCLAIMER_TEXT)


# ---------------------------------------------------------------------------
# Ambiguous Clause Mapping
# ---------------------------------------------------------------------------

class AIClauseMappingRequest(BaseModel):
    """Request to classify an ambiguous clause snippet."""
    clause_excerpt: str
    document_name: str


class AIClauseMappingResponse(BaseModel):
    """Mapping of ambiguous clause to domain rule catalog."""
    mapped_rule_id: Optional[str] = Field(description="e.g. 'COMP-001' or None if unrelated")
    category: Optional[str] = Field(description="e.g. 'compensation', 'notice_period'")
    confidence: float = Field(ge=0.0, le=1.0)
    rationale: str
    is_ai_generated: bool = Field(default=True)
    disclaimer: str = Field(default=AI_DISCLAIMER_TEXT)


# ---------------------------------------------------------------------------
# Verification Result Enrichment
# ---------------------------------------------------------------------------

class AIAssistanceResult(BaseModel):
    """
    Optional enrichment attached to VerificationResult when AI is enabled.
    Contains grounded explanations, semantic insights, and verification stats.
    """
    status: str = Field(description="'active' | 'unavailable' | 'partial' | 'skipped'")
    provider_used: str
    model_used: str
    explanations: Dict[str, AIExplanationResponse] = Field(default_factory=dict)
    semantic_insights: List[str] = Field(default_factory=list)
    grounding_stats: Dict[str, int] = Field(default_factory=dict)
    disclaimer: str = Field(default=AI_DISCLAIMER_TEXT)
